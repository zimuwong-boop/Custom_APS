"""Resolve with pip-tools; lock official PyPI release hashes without downloading every wheel."""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / ".tools"
PYTHON = ROOT / ".venv/bin/python"
PIN = re.compile(r"^([A-Za-z0-9_.-]+)==([^\s;]+)$")


def release_hashes(pin: tuple[str, str]) -> tuple[str, list[str]]:
    name, version = pin
    url = f"https://pypi.org/pypi/{urllib.parse.quote(name)}/{urllib.parse.quote(version)}/json"
    with urllib.request.urlopen(url, timeout=60) as response:
        release = json.load(response)
    if release["info"]["version"] != version:
        raise ValueError(f"Unexpected version for {name}: {release['info']['version']}")
    hashes = sorted(
        {
            artifact["digests"]["sha256"]
            for artifact in release["urls"]
            if not artifact.get("yanked", False)
        }
    )
    if not hashes or any(not re.fullmatch(r"[a-f0-9]{64}", digest) for digest in hashes):
        raise ValueError(f"Invalid official SHA-256 release data for {name}=={version}")
    return f"{name}=={version}", hashes


def lock(group: str) -> None:
    source = ROOT / "requirements" / f"{group}.in"
    resolved = TOOLS / f"{group}-resolved.txt"
    target = ROOT / "requirements" / f"{group}.txt"
    print(f"Resolving {group} dependencies with pip-tools...", flush=True)
    subprocess.run(
        [
            str(PYTHON),
            "-m",
            "piptools",
            "compile",
            "--quiet",
            "--allow-unsafe",
            "--strip-extras",
            "--cache-dir",
            str(TOOLS / "pip-tools-cache"),
            "--pip-args",
            "--timeout=30 --retries=1",
            "--output-file",
            str(resolved),
            str(source),
        ],
        cwd=ROOT,
        check=True,
    )
    pins = []
    for line in resolved.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        match = PIN.fullmatch(line)
        if not match:
            raise ValueError(f"Unsupported lock entry; review explicitly: {line}")
        pins.append(match.groups())
    if not pins:
        raise ValueError("Resolver produced no dependencies.")
    print(f"Fetching official release hashes for {len(pins)} {group} dependencies...", flush=True)
    with ThreadPoolExecutor(max_workers=6) as pool:
        releases = list(pool.map(release_hashes, pins))
    lines = [
        "# Generated by: .venv/bin/python scripts/lock_requirements.py",
        "# Versions resolved by pip-tools; SHA-256 values from official PyPI release JSON.",
        "# Includes all non-yanked release artifacts for macOS development/Linux deployment.",
        "# Install using: python -m pip install --require-hashes -r requirements/" + group + ".txt",
        "",
    ]
    for name, hashes in sorted(releases, key=lambda entry: entry[0].lower()):
        lines.append(name + " \\")
        lines.extend(
            "    --hash=sha256:" + digest + (" \\" if index < len(hashes) - 1 else "")
            for index, digest in enumerate(hashes)
        )
    temporary = target.with_suffix(".txt.tmp")
    temporary.write_text("\n".join(lines) + "\n")
    temporary.replace(target)
    print(f"Locked {len(pins)} packages: {target.relative_to(ROOT)}", flush=True)


def main() -> None:
    TOOLS.mkdir(exist_ok=True)
    os.environ.setdefault("PIP_CERT", str(TOOLS / "cacert.pem"))
    os.environ.setdefault("SSL_CERT_FILE", str(TOOLS / "cacert.pem"))
    os.environ.setdefault("PIP_CACHE_DIR", str(TOOLS / "pip-cache"))
    groups = sys.argv[1:] or ["base", "dev"]
    if any(group not in {"base", "dev"} for group in groups):
        raise SystemExit("Usage: lock_requirements.py [base] [dev]")
    for group in groups:
        lock(group)


if __name__ == "__main__":
    main()
